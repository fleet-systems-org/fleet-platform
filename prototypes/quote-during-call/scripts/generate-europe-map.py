"""Generate the decorative N8a map. Python 3 standard library only; no private input."""
import hashlib
import json
import math
from pathlib import Path
from urllib.request import urlopen

SOURCE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson"


def project(point):
    lon, lat = point[:2]
    # Mercator window -16..40 E, 32..67 N.
    y = lambda latitude: math.log(math.tan(math.pi / 4 + math.radians(latitude) / 2))
    return [round((lon + 16) / 56 * 900, 1), round((y(67) - y(lat)) / (y(67) - y(32)) * 750, 1)]


def clip(ring):
    for axis, bound, lower in [(0, -16, True), (0, 40, False), (1, 32, True), (1, 67, False)]:
        result = []
        for start, end in zip(ring[-1:] + ring[:-1], ring):
            inside = lambda p: p[axis] >= bound if lower else p[axis] <= bound
            if inside(start) != inside(end):
                ratio = (bound - start[axis]) / (end[axis] - start[axis])
                result.append([start[0] + ratio * (end[0] - start[0]), start[1] + ratio * (end[1] - start[1])])
            if inside(end):
                result.append(end)
        ring = result
    return ring


with urlopen(SOURCE, timeout=60) as response:
    raw = response.read()
paths = []
for feature in json.loads(raw)["features"]:
    geometry = feature["geometry"]
    polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    for polygon in polygons:
        for ring in polygon:
            points = [project(p) for p in clip(ring)]
            simplified = []
            for point in points:
                if not simplified or math.dist(point, simplified[-1]) >= 1.5:
                    simplified.append(point)
            if len(simplified) > 2:
                paths.append("M" + "L".join(f"{x},{y}" for x, y in simplified) + "Z")
# New illustrative arcs: Porto–Bordeaux–Lyon, Bilbao–Hamburg, Lyon–Ljubljana,
# Hamburg–Gdansk and Ljubljana–Budapest. Not road routing or operational data.
cities = [project(p) for p in [(-8.61, 41.15), (-0.58, 44.84), (4.84, 45.76), (-2.94, 43.26), (9.99, 53.55), (14.51, 46.06), (18.65, 54.35), (19.04, 47.50)]]
routes = []
for a, b in [(0, 1), (1, 2), (3, 4), (2, 5), (4, 6), (5, 7)]:
    x, y = cities[a]
    u, v = cities[b]
    routes.append(f"M{x},{y}Q{round((x+u)/2-25,1)},{round((y+v)/2-40,1)} {u},{v}")
output = f"// Generated by scripts/generate-europe-map.py from Natural Earth ne_50m_land.\n// Source: {SOURCE}\n// License: public domain. https://www.naturalearthdata.com/about/terms-of-use/\n// Source SHA-256: {hashlib.sha256(raw).hexdigest()}\n"
output += f"export const europeLand = {json.dumps(''.join(paths))};\nexport const demoRoutes = {json.dumps(routes)};\nexport const demoCities = {json.dumps(cities)};\n"
assert len(output.encode()) <= 120_000
Path(__file__).resolve().parents[1].joinpath("src/app/europe-map.ts").write_text(output)
print(f"Generated map: {len(output.encode())} bytes")
